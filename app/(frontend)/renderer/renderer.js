function parseOBJ(objText) {
  const vs = [];
  const faces = [];

  const lines = objText.split('\n');

  for (let line of lines) {
    line = line.trim();

    // 1. Parse Vertices (v x y z)
    if (line.startsWith('v ')) {
      const parts = line.split(/\s+/);
      vs.push({
        x: parseFloat(parts[1]),
        y: parseFloat(parts[2]),
        z: parseFloat(parts[3])
      });
    }

    // 2. Parse Faces (f v1/vt1/vn1 v2/vt2/vn2 v3/vt3/vn3)
    else if (line.startsWith('f ')) {
    const parts = line.split(/\s+/).slice(1); // ['107//223', '84//223', '71//223']

    const faceIndices = parts.map(part => {
        // Split "107//223" by "/" -> ['107', '', '223']
        const vertexIndex = part.split('/')[0]; 
        
        // Convert to number and subtract 1 (1-based to 0-based index)
        return parseInt(vertexIndex, 10) - 1; 
    });

    faces.push(faceIndices); // Outputs: [106, 83, 70]
    }
  }

  return { vs, faces };
}

